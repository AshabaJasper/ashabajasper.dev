/**
 * Writes src/data/tech-logos.ts from the simple-icons package (CC0 1.0), so
 * the site ships only the few dozen paths it draws instead of the whole set.
 * Run `npm run logos` after adding a slug below or upgrading simple-icons.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import * as icons from "simple-icons";

const SLUGS = [
  "nextdotjs", "react", "typescript", "javascript", "html5", "css", "tailwindcss", "bootstrap", "jquery", "vite",
  "nestjs", "nodedotjs", "prisma", "drizzle", "zod", "postgresql", "mysql", "sqlite", "mongodb", "redis", "supabase",
  "firebase", "php", "wordpress", "woocommerce", "flutter", "dart", "android", "apple", "docker", "kubernetes",
  "githubactions", "netlify", "vercel", "git", "linux", "gnubash", "python", "r", "cplusplus", "dotnet", "pytorch",
  "tensorflow", "keras", "scikitlearn", "pandas", "numpy", "opencv", "huggingface", "googlegemini", "claude",
  "apacheairflow", "apachespark", "sqlalchemy", "dask", "grafana", "plotly", "mlflow", "dvc", "googlecloud",
  "googlebigquery", "fastapi", "django", "flask", "graphql", "elasticstack", "googleanalytics", "github", "x",
  "spring", "kaggle",
];

/** A brand colour close to black or white disappears on one of the two canvases; those use the text colour. */
function usable(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  return lum > 0.12 && lum < 0.85;
}

const entries = SLUGS.map((slug) => {
  const key = `si${slug[0].toUpperCase()}${slug.slice(1)}`;
  const icon = icons[key];
  if (!icon) throw new Error(`simple-icons has no ${slug}`);
  return `  ${JSON.stringify(slug)}: { title: ${JSON.stringify(icon.title)}, hex: ${usable(icon.hex) ? JSON.stringify(`#${icon.hex}`) : "null"}, path: ${JSON.stringify(icon.path)} },`;
});

const out = `// Generated by scripts/generate-tech-logos.mjs from simple-icons (CC0 1.0). Do not edit by hand.

export interface LogoData {
  title: string;
  /** Brand colour, or null when it would vanish on the light or dark canvas. */
  hex: string | null;
  /** SVG path on a 24 by 24 grid. */
  path: string;
}

export const LOGOS = {
${entries.join("\n")}
} as const satisfies Record<string, LogoData>;

export type LogoSlug = keyof typeof LOGOS;
`;

writeFileSync(join(process.cwd(), "src", "data", "tech-logos.ts"), out);
console.log(`Wrote ${SLUGS.length} logos.`);
